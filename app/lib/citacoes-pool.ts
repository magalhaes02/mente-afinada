function hashString(s: string): number {
  let h = 5381;
  for (let i = 0; i < s.length; i++) {
    h = ((h << 5) + h + s.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

export function buildPoolQuote(dateKey: string): Quote {
  return QUOTE_POOL[hashString(dateKey + "-q") % QUOTE_POOL.length];
}
